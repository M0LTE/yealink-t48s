"""mkfont.py OUT.h [wf]: render DejaVu fonts into 8-bit alpha glyph tables (ASCII 32-126).
Default set for native/t48ui.c and membanner.c; "wf" is the smaller set for native/waterfall.c."""
import sys
from PIL import Image, ImageDraw, ImageFont
D = "/usr/share/fonts/truetype/dejavu/"
FONTS = [("f_small", "DejaVuSans.ttf", 18), ("f_mono", "DejaVuSansMono.ttf", 19),
         ("f_bold", "DejaVuSans-Bold.ttf", 22), ("f_big", "DejaVuSans-Bold.ttf", 34)]
if sys.argv[2:] == ["wf"]:
    FONTS = [("f_tiny", "DejaVuSansMono.ttf", 12), ("f_small", "DejaVuSans.ttf", 14),
             ("f_mono", "DejaVuSansMono.ttf", 14), ("f_bold", "DejaVuSans-Bold.ttf", 16),
             ("f_head", "DejaVuSans-Bold.ttf", 19), ("f_big", "DejaVuSans-Bold.ttf", 28)]
out = ["/* generated by tools/mkfont.py from DejaVu fonts (Bitstream Vera licence); do not edit */",
       "struct glyph { short adv, w, h, xoff, yoff; unsigned off; };",
       "struct font { short ascent, height; const struct glyph *g; const unsigned char *a; };"]
for name, file, size in FONTS:
    f = ImageFont.truetype(D + file, size)
    ascent, descent = f.getmetrics()
    glyphs, alpha = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        adv = round(f.getlength(ch))
        box = f.getbbox(ch)  # relative to the text origin at the top of the ascent
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        off = len(alpha)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
            alpha += im.tobytes()
        glyphs.append((adv, w, h, box[0], box[1], off))
    out.append(f"static const unsigned char {name}_a[] = {{{','.join(str(b) for b in alpha)}}};")
    out.append(f"static const struct glyph {name}_g[] = {{" +
               ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};")
    out.append(f"static const struct font {name} = {{{ascent}, {ascent + descent}, {name}_g, {name}_a}};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print(sys.argv[1], sum(len(l) for l in out), "bytes of source")
