"""mkfont.py [SRCDIR [FONTDIR]]: render the font families into 8-bit alpha glyph tables
(ASCII 32-126) for libt48: SRCDIR/fonts_gen.c (B612, which every program has) and
SRCDIR/fonts_FAMILY.c (the others, which only the shell links). The output is
committed, so building libt48 needs neither Python nor the font files. Run
`make fonts` in libt48/ after changing the lists below.

A family is the eight faces libt48 offers, each: name, file, pixel size, weight (for a
variable font, else None), characters (None = all of ASCII 32-126). A face that is
the same file, size and weight as one of B612's uses B612's tables."""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

DIGITS = "0123456789:.- "
FAMILIES = [
    # B612, drawn for aircraft cockpit displays: open shapes that hold up on a coarse screen
    ("b612", "B612 and B612 Mono (SIL Open Font Licence 1.1)", [
        ("tiny", "B612Mono-Regular.ttf", 12, None, None),
        ("small", "B612-Regular.ttf", 15, None, None),
        ("normal", "B612-Regular.ttf", 19, None, None),
        ("bold", "B612-Bold.ttf", 19, None, None),
        ("mono", "B612Mono-Regular.ttf", 15, None, None),
        ("head", "B612-Bold.ttf", 26, None, None),
        ("big", "B612-Bold.ttf", 40, None, None),
        ("huge", "B612-Bold.ttf", 104, None, DIGITS)]),
    # IBM Plex Sans: an engineer's grotesque, plain figures
    ("plex", "IBM Plex Sans and IBM Plex Mono (SIL Open Font Licence 1.1)", [
        ("tiny", "IBMPlexMono-Regular.ttf", 12, None, None),
        ("small", "IBMPlexSans[wdth,wght].ttf", 15, (450, 100), None),
        ("normal", "IBMPlexSans[wdth,wght].ttf", 19, (400, 100), None),
        ("bold", "IBMPlexSans[wdth,wght].ttf", 19, (600, 100), None),
        ("mono", "IBMPlexMono-Regular.ttf", 15, None, None),
        ("head", "IBMPlexSans[wdth,wght].ttf", 26, (600, 100), None),
        ("big", "IBMPlexSans[wdth,wght].ttf", 40, (600, 100), None),
        ("huge", "IBMPlexSans[wdth,wght].ttf", 104, (700, 100), DIGITS)]),
    # Figtree: a round, even geometric. It has no fixed-width face: B612 Mono stands in
    ("figtree", "Figtree (SIL Open Font Licence 1.1); the fixed-width faces are B612 Mono", [
        ("tiny", "B612Mono-Regular.ttf", 12, None, None),
        ("small", "Figtree[wght].ttf", 15, 500, None),
        ("normal", "Figtree[wght].ttf", 19, 500, None),
        ("bold", "Figtree[wght].ttf", 19, 700, None),
        ("mono", "B612Mono-Regular.ttf", 15, None, None),
        ("head", "Figtree[wght].ttf", 26, 700, None),
        ("big", "Figtree[wght].ttf", 40, 700, None),
        ("huge", "Figtree[wght].ttf", 104, 800, DIGITS)]),
]

here = os.path.dirname(os.path.abspath(__file__))
srcdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "src")
fontdir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "fonts")


def render(file, size, weight, chars):
    f = ImageFont.truetype(os.path.join(fontdir, file), size)
    if weight is not None:
        f.set_variation_by_axes(list(weight) if isinstance(weight, tuple) else [weight])
    ascent, descent = f.getmetrics()
    glyphs, alpha = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        if chars is not None and ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = round(f.getlength(ch))
        box = f.getbbox(ch)  # relative to the text origin at the top of the ascent
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        off = len(alpha)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
            alpha += im.tobytes()
        glyphs.append((adv, w, h, box[0], box[1], off))
    return ascent, ascent + descent, glyphs, alpha


shared = {}  # (file, size, weight, chars) -> the face of B612 that is the same
for family, credit, faces in FAMILIES:
    first = family == "b612"
    out = ["// SPDX-License-Identifier: AGPL-3.0-or-later",
           f"/* generated by libt48/tools/mkfont.py from {credit}; do not edit */",
           '#include "t48.h"']
    inits, total = [], 0
    for name, file, size, weight, chars in faces:
        key = (file, size, weight, chars)
        if key in shared:
            ascent, height, sym = shared[key]
            out.append(f"extern const unsigned char {sym}_a[];")
            out.append(f"extern const t48_glyph {sym}_g[];")
        else:
            ascent, height, glyphs, alpha = render(file, size, weight, chars)
            sym = f"t48_{family}_{name}"
            total += len(alpha) + 16 * len(glyphs)
            out.append(f"const unsigned char {sym}_a[] = {{{','.join(str(b) for b in alpha)}}};")
            out.append(f"const t48_glyph {sym}_g[] = {{" + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};")
            if first:
                shared[key] = (ascent, height, sym)
        inits.append((name, f"{{{ascent}, {height}, {sym}_g, {sym}_a}}"))
    out.append(f"const t48_font_family t48_fonts_{family} = {{\"{family}\", {{" + ", ".join(i for _, i in inits) + "}};")
    if first:
        out.append("/* the faces in use: B612 until t48_fonts_use says otherwise */")
        out += [f"t48_font t48_font_{name} = {init};" for name, init in inits]
    dest = os.path.join(srcdir, "fonts_gen.c" if first else f"fonts_{family}.c")
    open(dest, "w").write("\n".join(out) + "\n")
    print(f"{family}: {total} bytes of tables, {os.path.normpath(dest)}")
