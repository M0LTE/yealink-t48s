"""mkfont.py OUT.c [SET [FONTDIR]]: render a set of fonts into 8-bit alpha glyph tables
(ASCII 32-126) for libt48. The output is committed, so building libt48 needs neither
Python nor the font files. Run `make fonts` in libt48/ after changing the lists below.

A set is the eight faces libt48 offers, each: name, file, pixel size, weight (for a
variable font, else None), characters (None = all of ASCII 32-126)."""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu/"
DIGITS = "0123456789:.- "
SETS = {
    # the faces the firmware began with
    "dejavu": ("DejaVu fonts (Bitstream Vera licence)", [
        ("tiny", DEJAVU + "DejaVuSansMono.ttf", 12, None, None),
        ("small", DEJAVU + "DejaVuSans.ttf", 15, None, None),
        ("normal", DEJAVU + "DejaVuSans.ttf", 19, None, None),
        ("bold", DEJAVU + "DejaVuSans-Bold.ttf", 19, None, None),
        ("mono", DEJAVU + "DejaVuSansMono.ttf", 15, None, None),
        ("head", DEJAVU + "DejaVuSans-Bold.ttf", 26, None, None),
        ("big", DEJAVU + "DejaVuSans-Bold.ttf", 40, None, None),
        ("huge", DEJAVU + "DejaVuSans-Bold.ttf", 104, None, DIGITS)]),
    # B612, drawn for aircraft cockpit displays: open shapes that hold up on a coarse screen
    "b612": ("B612 and B612 Mono (SIL Open Font Licence 1.1)", [
        ("tiny", "B612Mono-Regular.ttf", 12, None, None),
        ("small", "B612-Regular.ttf", 15, None, None),
        ("normal", "B612-Regular.ttf", 19, None, None),
        ("bold", "B612-Bold.ttf", 19, None, None),
        ("mono", "B612Mono-Regular.ttf", 15, None, None),
        ("head", "B612-Bold.ttf", 26, None, None),
        ("big", "B612-Bold.ttf", 40, None, None),
        ("huge", "B612-Bold.ttf", 104, None, DIGITS)]),
    # IBM Plex Sans: an engineer's grotesque, plain figures
    "plex": ("IBM Plex Sans and IBM Plex Mono (SIL Open Font Licence 1.1)", [
        ("tiny", "IBMPlexMono-Regular.ttf", 12, None, None),
        ("small", "IBMPlexSans[wdth,wght].ttf", 15, (450, 100), None),
        ("normal", "IBMPlexSans[wdth,wght].ttf", 19, (400, 100), None),
        ("bold", "IBMPlexSans[wdth,wght].ttf", 19, (600, 100), None),
        ("mono", "IBMPlexMono-Regular.ttf", 15, None, None),
        ("head", "IBMPlexSans[wdth,wght].ttf", 26, (600, 100), None),
        ("big", "IBMPlexSans[wdth,wght].ttf", 40, (600, 100), None),
        ("huge", "IBMPlexSans[wdth,wght].ttf", 104, (700, 100), DIGITS)]),
    # Figtree: a round, even geometric
    "figtree": ("Figtree (SIL Open Font Licence 1.1); the fixed-width faces are DejaVu Sans Mono (Bitstream Vera licence)", [
        ("tiny", DEJAVU + "DejaVuSansMono.ttf", 12, None, None),
        ("small", "Figtree[wght].ttf", 15, 500, None),
        ("normal", "Figtree[wght].ttf", 19, 500, None),
        ("bold", "Figtree[wght].ttf", 19, 700, None),
        ("mono", DEJAVU + "DejaVuSansMono.ttf", 15, None, None),
        ("head", "Figtree[wght].ttf", 26, 700, None),
        ("big", "Figtree[wght].ttf", 40, 700, None),
        ("huge", "Figtree[wght].ttf", 104, 800, DIGITS)]),
}

dest = sys.argv[1]
which = sys.argv[2] if len(sys.argv) > 2 else "b612"
fontdir = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fonts")
credit, fonts = SETS[which]
out = ["// SPDX-License-Identifier: AGPL-3.0-or-later",
       f"/* generated by libt48/tools/mkfont.py ({which}) from {credit}; do not edit */",
       '#include "t48.h"']
for name, file, size, weight, chars in fonts:
    f = ImageFont.truetype(file if os.path.isabs(file) else os.path.join(fontdir, file), size)
    if weight is not None:
        f.set_variation_by_axes(list(weight) if isinstance(weight, tuple) else [weight])
    ascent, descent = f.getmetrics()
    glyphs, alpha = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        if chars is not None and ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = round(f.getlength(ch))
        box = f.getbbox(ch)  # relative to the text origin at the top of the ascent
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        off = len(alpha)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
            alpha += im.tobytes()
        glyphs.append((adv, w, h, box[0], box[1], off))
    out.append(f"static const unsigned char {name}_a[] = {{{','.join(str(b) for b in alpha)}}};")
    out.append(f"static const t48_glyph {name}_g[] = {{" +
               ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};")
    out.append(f"const t48_font t48_font_{name} = {{{ascent}, {ascent + descent}, {name}_g, {name}_a}};")
open(dest, "w").write("\n".join(out) + "\n")
print(dest, sum(len(l) for l in out), "bytes of source")
