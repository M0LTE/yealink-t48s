"""mkfont.py OUT.c: render DejaVu fonts into 8-bit alpha glyph tables (ASCII 32-126)
for libt48. The output is committed, so building libt48 needs neither Python nor the
font files. Run `make fonts` in libt48/ after changing the list below."""
import sys
from PIL import Image, ImageDraw, ImageFont
D = "/usr/share/fonts/truetype/dejavu/"
DIGITS = "0123456789:.- "
# name, file, pixel size, characters (None = all of ASCII 32-126)
FONTS = [("tiny", "DejaVuSansMono.ttf", 12, None),
         ("small", "DejaVuSans.ttf", 15, None),
         ("normal", "DejaVuSans.ttf", 19, None),
         ("bold", "DejaVuSans-Bold.ttf", 19, None),
         ("mono", "DejaVuSansMono.ttf", 15, None),
         ("head", "DejaVuSans-Bold.ttf", 26, None),
         ("big", "DejaVuSans-Bold.ttf", 40, None),
         ("huge", "DejaVuSans-Bold.ttf", 104, DIGITS)]
out = ["// SPDX-License-Identifier: AGPL-3.0-or-later",
       "/* generated by libt48/tools/mkfont.py from DejaVu fonts (Bitstream Vera licence); do not edit */",
       '#include "t48.h"']
for name, file, size, chars in FONTS:
    f = ImageFont.truetype(D + file, size)
    ascent, descent = f.getmetrics()
    glyphs, alpha = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        if chars is not None and ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = round(f.getlength(ch))
        box = f.getbbox(ch)  # relative to the text origin at the top of the ascent
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        off = len(alpha)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
            alpha += im.tobytes()
        glyphs.append((adv, w, h, box[0], box[1], off))
    out.append(f"static const unsigned char {name}_a[] = {{{','.join(str(b) for b in alpha)}}};")
    out.append(f"static const t48_glyph {name}_g[] = {{" +
               ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};")
    out.append(f"const t48_font t48_font_{name} = {{{ascent}, {ascent + descent}, {name}_g, {name}_a}};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print(sys.argv[1], sum(len(l) for l in out), "bytes of source")
